class Task:
    """
    Represents a computational task generated by an IoT user.

    The task attributes are used by:
        - Resource-aware filtering
        - Network-resource calculation
        - DGWO optimization

    The computational requirement of the task is represented
    by its workload in CPU cycles.

    The amount of CPU processing capacity allocated to the
    task is determined during the resource-allocation stage.
    """

    def __init__(
        self,
        task_id,
        workload,
        memory_required,
        data_size,
        max_delay,
        source_user_id
    ):
        # ==================================================
        # Task identification
        # ==================================================

        self.task_id = task_id

        # ==================================================
        # Computational requirement
        # ==================================================
        #
        # Total computational workload.
        #
        # Unit: CPU cycles
        # ==================================================

        self.workload = workload

        # ==================================================
        # Memory requirement
        # ==================================================
        #
        # Required RAM.
        #
        # Unit: MB
        # ==================================================

        self.memory_required = memory_required

        # ==================================================
        # Input data size
        # ==================================================
        #
        # Unit: MB
        # ==================================================

        self.data_size = data_size

        # ==================================================
        # Delay requirement
        # ==================================================
        #
        # Maximum tolerable total task delay.
        #
        # Unit: seconds
        # ==================================================

        self.max_delay = max_delay

        # ==================================================
        # Task source
        # ==================================================
        #
        # ID of the IoT user generating the task.
        # ==================================================

        self.source_user_id = source_user_id

    def __repr__(self):
        """
        Return a readable representation of the task.
        """

        return (
            f"Task("
            f"id={self.task_id}, "
            f"workload={self.workload}, "
            f"memory={self.memory_required} MB, "
            f"data_size={self.data_size} MB, "
            f"max_delay={self.max_delay} s, "
            f"source_user={self.source_user_id}"
            f")"
        )